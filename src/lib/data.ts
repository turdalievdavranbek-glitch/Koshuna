export function propertyIsLiving(type: string) {
  return LIVING_PROPERTY.has(type);
}

export function propertyShowsRooms(type: string) {
  return ROOMS_PROPERTY.has(type);
}

export function propertyShowsStock(type: string) {
  return STOCK_PROPERTY.has(type);
}

