export function housingDealLabel(
  listing: { dealKind?: string; stockKind?: string },
  t: Dict,
): string {
  if (listing.dealKind === "buy") {
    if (listing.stockKind === "newbuild") return `${t.dealBuy} · ${t.stockNew}`;
    if (listing.stockKind === "resale") return `${t.dealBuy} · ${t.stockResale}`;
    return t.dealBuy;
  }
  if (listing.dealKind === "short") return t.dealShort;
  if (listing.dealKind === "share") return t.dealShare;
  return t.dealLong;
}

export function listingChipLabel(
  listing: {
    section: SectionId;
    category?: string;
    goodsKind?: string;
    housingKind?: string;
    realtyGroup?: string;
    realtySub?: string;
    realtyKind?: string;
    carMake?: string;
    carModel?: string;
    techBrand?: string;
    techModel?: string;
    animalKind?: string;
    jobRole?: string;
    jobSphere?: string;
    dealKind?: string;
    stockKind?: string;
  },
  t: Dict,
): string {
  if (listing.section === "rent") {
    if (listing.realtyKind && t.realtyKinds[listing.realtyKind]) return t.realtyKinds[listing.realtyKind];
    if (listing.realtyGroup && t.realtyGroups[listing.realtyGroup]) return t.realtyGroups[listing.realtyGroup];
    if (listing.housingKind && t.propertyTypes[listing.housingKind]) {
      return t.propertyTypes[listing.housingKind];
    }
    return housingDealLabel(listing, t);
  }
  if (listing.section === "cars" || listing.section === "car-rental") {
    const make = listing.carMake ? t.carMakes[listing.carMake] : "";
    const model = listing.carModel ? t.carModels[listing.carModel] : "";
    const name = [make, model].filter(Boolean).join(" ");
    if (name) return name;
    return listing.section === "car-rental" ? t.autoRent : t.autoSale;
  }
  if (listing.section === "vacancies") {
    if (listing.jobRole && t.jobRoles[listing.jobRole]) return t.jobRoles[listing.jobRole];
    if (listing.jobSphere && t.jobSpheres[listing.jobSphere]) return t.jobSpheres[listing.jobSphere];
    return t.sectionNames.vacancies;
  }
  if (listing.section === "animals" && listing.animalKind && t.animalKinds[listing.animalKind]) {
    return t.animalKinds[listing.animalKind];
  }
  if (listing.section === "secondhand") {
    const brand = listing.techBrand ? t.techBrands[listing.techBrand] : "";
    const model = listing.techModel ? t.techModels[listing.techModel] : "";
    const name = [brand, model].filter(Boolean).join(" ");
    if (name) return name;
  }
  if (listing.section === "shops") {
    if (listing.category && t.shopKinds[listing.category]) return t.shopKinds[listing.category];
    if (listing.category && t.shopCats[listing.category]) return t.shopCats[listing.category];
    return t.shopBadge;
  }
  if (listing.goodsKind && t.goodsKinds[listing.goodsKind]) return t.goodsKinds[listing.goodsKind];
  if (listing.category && t.cats[listing.category]) return t.cats[listing.category];
  return t.sectionNames[listing.section];
}

export function postedLabel(
  listing: { postedAgo: string; postedAt?: string },
  t: Dict,
): string {
  const key = listing.postedAt ? postedKeyFrom(listing.postedAt) : listing.postedAgo;
  return t.ago[key] ?? listing.postedAgo;
}

function postedKeyFrom(iso: string): string {
  const ms = Date.now() - new Date(iso).getTime();
  if (!Number.isFinite(ms) || ms < 3_600_000) return "now";
  const h = Math.floor(ms / 3_600_000);
  if (h < 3) return "2h";
  if (h < 4) return "3h";
  if (h < 5) return "4h";
  if (h < 7) return "6h";
  if (h < 8) return "7h";
  if (h < 9) return "8h";
  if (h < 12) return "9h";
  if (h < 20) return "12h";
  if (h < 36) return "1d";
  if (h < 60) return "2d";
  if (h < 96) return "3d";
  return "5d";
}

