export type Dict = typeof ru;

export function searchPlaceholder(section: SectionId | null | undefined, t: Dict): string {
  switch (section) {
    case "rent":
      return t.searchRent;
    case "secondhand":
      return t.searchSecondhand;
    case "cars":
    case "car-rental":
      return t.searchCars;
    case "services":
      return t.searchServices;
    case "stays":
      return t.searchStays;
    case "animals":
      return t.searchAnimals;
    case "construction":
      return t.searchConstruction;
    case "restaurants":
      return t.searchRestaurants;
    default:
      return t.searchPh;
  }
}

export function listingTitle(listing: { title: string; titleKy: string; titleEn: string }, lang: Lang) {
  if (lang === "ky") return listing.titleKy;
  if (lang === "en") return listing.titleEn;
  return listing.title;
}

export function housingDealLabel(
  listing: { dealKind?: string; stockKind?: string },
  t: Dict,
): string {
  if (listing.dealKind === "buy") {
    if (listing.stockKind === "newbuild") return `${t.dealBuy} · ${t.stockNew}`;
    if (listing.stockKind === "resale") return `${t.dealBuy} · ${t.stockResale}`;
    return t.dealBuy;
  }
  if (listing.dealKind === "short") return t.dealShort;
  return t.dealLong;
}

export function listingChipLabel(
  listing: {
    section: SectionId;
    category?: string;
    goodsKind?: string;
    housingKind?: string;
    carMake?: string;
    carModel?: string;
    techBrand?: string;
    techModel?: string;
    animalKind?: string;
    dealKind?: string;
    stockKind?: string;
  },
  t: Dict,
): string {
  if (listing.section === "rent") {
    if (listing.housingKind && t.propertyTypes[listing.housingKind]) {
      return t.propertyTypes[listing.housingKind];
    }
    return housingDealLabel(listing, t);
  }
  if (listing.section === "cars" || listing.section === "car-rental") {
    const make = listing.carMake ? t.carMakes[listing.carMake] : "";
    const model = listing.carModel ? t.carModels[listing.carModel] : "";
    const name = [make, model].filter(Boolean).join(" ");
    if (name) return name;
    return listing.section === "car-rental" ? t.autoRent : t.autoSale;
  }
  if (listing.section === "animals" && listing.animalKind && t.animalKinds[listing.animalKind]) {
    return t.animalKinds[listing.animalKind];
  }
  if (listing.section === "secondhand") {
    const brand = listing.techBrand ? t.techBrands[listing.techBrand] : "";
    const model = listing.techModel ? t.techModels[listing.techModel] : "";
    const name = [brand, model].filter(Boolean).join(" ");
    if (name) return name;
  }
  if (listing.goodsKind && t.goodsKinds[listing.goodsKind]) return t.goodsKinds[listing.goodsKind];
  if (listing.category && t.cats[listing.category]) return t.cats[listing.category];
  return t.sectionNames[listing.section];
}

