export function searchPlaceholder(section: SectionId | null | undefined, t: Dict): string {
  switch (section) {
    case "rent":
      return t.searchRent;
    case "secondhand":
      return t.searchSecondhand;
    case "cars":
    case "car-rental":
      return t.searchCars;
    case "services":
      return t.searchServices;
    case "stays":
      return t.searchStays;
    case "animals":
      return t.searchAnimals;
    case "vacancies":
      return t.searchVacancies;
    case "construction":
      return t.searchConstruction;
    case "restaurants":
      return t.searchRestaurants;
    case "shops":
      return t.shopSearch;
    default:
      return t.searchPh;
  }
}

